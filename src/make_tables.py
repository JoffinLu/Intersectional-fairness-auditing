"""Generate flat LaTeX tables with explicit sources and Monte Carlo errors."""
import json
import numpy as np
import pandas as pd
from artifacts import ROOT

P=ROOT/'paper';A=ROOT/'analysis'
def esc(s):return str(s).replace('_',r'\_').replace('&',r'\&')
def table(name,columns,header,rows,caption,label):
    body='\n'.join(' & '.join(map(str,row))+r' \\' for row in rows)
    text=(f'% Generated by src/make_tables.py; source analysis/*.csv and retained results.\n'
      '\\begin{table}[t]\n\\centering\\small\n'
      f'\\caption{{{caption}}}\\label{{{label}}}\n'
      f'\\begin{{tabular}}{{{columns}}}\n\\toprule\n'+' & '.join(header)+r' \\'+'\n\\midrule\n'+body+
      '\n\\bottomrule\n\\end{tabular}\n\\end{table}\n')
    (P/name).write_text(text,encoding='utf-8')

def main():
    d=pd.read_csv(A/'dataset_table.csv');rows=[]
    labels={'adult':'Adult','diabetes':'Diabetes','acs_income':'ACS Income','acs_employment':'ACS Employment'}
    for r in d.itertuples():
        rows.append([labels[r.dataset],f'{r.rows:,}',f'{r.positive_audit_n:,}',r.registered_groups,
                     r.nonzero_positive_groups,r.zero_positive_groups,r.positive_lt10_groups,
                     f'{r.lr_audit_auc:.3f}/{r.hgb_audit_auc:.3f}'])
    table('table_data.tex','lrrrrrrr',['Task','Used $N$','$N^+_A$','$G$','$n_g>0$','$n_g=0$','$0<n_g<10$','AUC LR/HGB'],rows,
          'Original-data support and discrimination on the frozen audit split. Effective audit counts $N^+_A$ count positive labels; empty cells remain registered. AUC is descriptive and does not establish fairness.','tab:data')
    f=pd.read_csv(A/'valid_flags_all_main.csv');rows=[]
    names={'full_hb_holm':'Full HB','full_hoeffding_holm':'Full H',
           'split_uniform_holm':'Split uniform','split_size_holm':'Split size','split_raw_holm':'Split raw',
           'split_eb_holm':'Split EB','split_conflict_holm':'Split conflict'}
    for method,label in names.items():
        z=f[f.method==method];r=z.loc[z.fwer.idxmax()]
        rows.append([label,f'{100*r.fwer:.3f}',f'[{100*r.fwer_wilson_lower:.3f}, {100*r.fwer_wilson_upper:.3f}]',
                     int(r.groups),esc(r.family.replace('_',' '))])
    table('table_fwer.tex','lrrrl',['Method + Holm',r'Max FWER (\%)',r'95\% interval (\%)','$G$','Selected configuration'],rows,
          r'Maximum observed familywise false-flag frequency for each method over the 60 main configurations (2,000 repeats each). Intervals are pointwise Wilson intervals for the selected configuration, not simultaneous bounds on the maximum. Nominal FWER is 5\%; the construction is conservative.','tab:fwer')
    d=pd.read_csv(ROOT/'results/main_v1/summary.csv');rows=[]
    for n,gap in ((20,.1),(20,.3),(40,.2),(80,.2),(160,.2)):
        vals=[n,f'{gap:.2f}']
        for method in ('full_hb_holm','split_raw_holm','split_eb_holm','split_conflict_holm'):
            r=d[(d.kind=='flag')&(d.method==method)&(d.groups==32)&(d.family=='sparse_rare')&(d.target_n==n)&((d.effect_above_margin-gap).abs()<1e-8)].iloc[0]
            vals.append(f'{100*r.target_flag_rate:.2f} ({100*r.target_mcse:.2f})')
        rows.append(vals)
    table('table_power.tex','rrrrrr',['$n_*$',r'$\varepsilon$','Full HB','Split raw','Split EB','Split conflict'],rows,
          r'Target flagging percentages with Monte Carlo standard errors in parentheses, $G=32$, $\Delta=.05$, $c=.8$, $\rho=.1$, 2,000 repeats. All methods use the same total generated counts and the same HB confirmation engine; full data use all observations. $\varepsilon=\delta_* -\Delta$.','tab:power')
    controls=d[(d.kind=='flag')&(d.family!='sparse_rare')];rows=[]
    for sid in controls.scenario_id.drop_duplicates():
        z=controls[controls.scenario_id==sid];ref=z.iloc[0]
        raw=np.load(ROOT/f'results/main_v1/{sid}.npz')
        vals=[ref.family.replace('_',' '),int(ref.groups),int(ref.harmful_groups)]
        for method in ('full_hb_holm','split_raw_holm','split_conflict_holm'):
            r=z[z.method==method].iloc[0]
            if ref.harmful_groups:
                power=raw['flag__'+method][:,raw['harmful']].mean(axis=1)
                vals.append(f'{100*power.mean():.1f} ({100*power.std(ddof=1)/np.sqrt(len(power)):.1f})')
            else:vals.append('--')
        vals.append(f'{100*z.fwer.max():.2f}');rows.append(vals)
    table('table_controls.tex','lrrrrrr',['Control','$G$',r'$|\mathcal H|$','Full HB','Split raw','Conflict',r'Max FWER\%'],rows,
          r'Main control families: mean flagging power across genuinely harmed cells, in percent (MCSE), and maximum observed FWER among the seven valid-flag methods in each configuration, 2,000 repeats. MCSE uses the per-repetition average over harmed cells. A dash denotes no harmful cell. Pointwise uncertainty for every method/configuration is retained in the accompanying CSV.','tab:controls')
    d=pd.read_csv(A/'baseline_paired_details.csv');z=d[(d.source=='baselines')&(d.family=='sparse_rare')];rows=[]
    labels2={'raw':'Raw','moment_eb':'Moment EB','sr_point_adapter':'SR point','suremap_author_adapter':'SureMap'}
    for sid in z.scenario_id.drop_duplicates():
        for m,label in labels2.items():
            r=z[(z.scenario_id==sid)&(z.method==m)].iloc[0]
            rows.append([f'{int(r.target_n)}/{r.effect_above_margin:.2f}',label,
              f'{1000*r.macro_mse:.2f} ({1000*r.macro_mse_mcse:.2f})',f'{1000*r.target_mse:.2f}',
              f'{100*r.target_screen_rate:.1f} ({100*r.target_screen_mcse:.1f})'])
    table('table_estimators.tex','llrrr',[r'$n_*/\varepsilon$','Estimator',r'Macro MSE $\times10^3$',r'Target MSE $\times10^3$',r'Screen \%'],rows,
          'Point-estimator diagnostics in four prespecified sparse settings, 120 paired repeats. Parentheses are Monte Carlo standard errors. Screen means plug-in estimated group--complement disparity exceeds .05; these screens are not calibrated tests. SR is the local point adapter, without the original interval procedure.','tab:estimators')
    d=pd.read_csv(A/'semi_paired_flags.csv');z=d[d.method=='split_conflict_holm'];rows=[]
    for r in z.itertuples():
        rows.append([labels[r.dataset],r.model.upper(),'H' if r.geometry=='homogeneous' else 'V',
                     int(r.groups),f'{100*r.full_power:.1f}',f'{100*r.split_power:.1f}',
                     f'{100*r.paired_difference:+.1f} ({100*r.paired_mcse:.2f})'])
    table('table_semi.tex','lllrrrr',['Task','Model','Rates','$G_S$',r'Full \%',r'Conflict \%','Difference pp'],rows,
          r'Known-truth real-support results: all selected target cells have $n_*=10$ and $\delta_*=.25$; 1,000 repeats. H uses homogeneous baseline rates, V uses calibration-heterogeneous templates. Differences in percentage points use paired Monte Carlo standard errors. The tested complement is over the selected, rounded and capped family, not the original partition.','tab:semi')
    supplemental=ROOT/'results/support_sensitivity_v1/paired_comparisons.csv'
    if supplemental.exists():
        s=pd.read_csv(supplemental);all_support=pd.read_csv(supplemental.with_name('summary.csv'));rows=[]
        for sid in s.scenario_id.drop_duplicates():
            z=s[s.scenario_id==sid];raw=z[z.method=='split_raw_holm'].iloc[0];conf=z[z.method=='split_conflict_holm'].iloc[0]
            full_h=all_support[(all_support.scenario_id==sid)&(all_support.kind=='flag')&(all_support.method=='full_hoeffding_holm')].iloc[0]
            tasklabel=labels[raw.dataset].replace('ACS Income','ACS Inc.').replace('ACS Employment','ACS Emp.')
            rows.append([tasklabel+' '+raw.model.upper(),'C' if raw.count_geometry=='capped_1000' else 'U',
                         int(raw.target_n),f'{100*raw.full_power:.1f}',f'{100*full_h.target_flag_rate:.1f}',f'{100*raw.method_power:.1f}',
                         f'{100*conf.method_power:.1f}',f'{100*raw.paired_difference:+.1f} ({100*raw.paired_mcse:.2f})'])
        table('table_support.tex','llrrrrrr',['Task/model','Counts','$n_*$',r'HB\%',r'H\%',r'Raw\%',r'Conflict\%','Raw--HB pp'],rows,
              r'Prespecified support sensitivity, 1,000 repeats per configuration, generated contrast .25. HB and H are full-data engines; Raw and Conflict use split HB. C caps rounded counts at 1,000; U leaves rounded counts uncapped. Differences in percentage points have paired MCSE in parentheses. Only Adult has a count vector changed by the cap; C/U rows for the other tasks are independent Monte Carlo repeats of identical templates. The larger-target rule changes cell identity as well as count.','tab:support')
    # Explicit conflict-minus-raw paired diagnostics (not a new favorable method).
    from analyze_experiments import paired_flags
    p=paired_flags(ROOT/'results/main_v1');p=p[p.family=='sparse_rare']
    pivot=p.pivot(index='scenario_id',columns='method',values='split_power')
    diff=pivot.split_conflict_holm-pivot.split_raw_holm
    (A/'conflict_vs_raw_summary.json').write_text(json.dumps({'wins':int((diff>0).sum()),'ties':int((diff==0).sum()),
      'losses':int((diff<0).sum()),'min_difference':float(diff.min()),'max_difference':float(diff.max()),
      'mean_grid_difference':float(diff.mean()),'scope':'descriptive fixed grid, not a population probability or adjusted significance test'},indent=2),encoding='utf-8')
    print('Generated six tables and conflict-versus-raw evidence.')

if __name__=='__main__':main()
